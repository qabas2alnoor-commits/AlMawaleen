// ============================================
// hijri-settings.js
// إعدادات التقويم الهجري الإمامي
// مواقيت الولاء
// ============================================
//
// مصدر إعداد التصحيح:
// Supabase → app_settings → hijri_offset
//
// القيم المسموحة فقط:
// -1 = أخذ التاريخ الهجري لليوم الميلادي السابق
//  0 = بدون تعديل
// +1 = أخذ التاريخ الهجري لليوم الميلادي التالي
//
// مهم جدًا:
// لا يتم تعديل رقم اليوم الهجري مباشرة.
// لا يتم تغيير طول الشهر الهجري.
// لا يتم افتراض أن الشهر 29 أو 30 يومًا.
//
// calendar.js هو المسؤول عن تطبيق التصحيح
// على التاريخ الهجري فقط.
// ============================================


// ============================================
// قيمة التصحيح الحالية
// ============================================

let hijriOffset = 0;


// ============================================
// تحميل إعداد التصحيح من Supabase
// ============================================

async function loadHijriOffset() {

    // ----------------------------------------
    // القيمة الافتراضية الآمنة
    // ----------------------------------------

    hijriOffset = 0;


    try {

        // ----------------------------------------
        // التأكد من توفر Supabase
        // ----------------------------------------

        if (
            typeof supabaseClient === "undefined"
        ) {

            console.warn(
                "Supabase غير متوفر، سيتم استخدام hijri_offset = 0"
            );

            return hijriOffset;

        }


        // ----------------------------------------
        // قراءة إعداد hijri_offset
        // ----------------------------------------

        const {
            data,
            error
        } = await supabaseClient
            .from("app_settings")
            .select("setting_value")
            .eq(
                "setting_key",
                "hijri_offset"
            )
            .maybeSingle();


        // ----------------------------------------
        // معالجة الخطأ
        // ----------------------------------------

        if (error) {

            console.error(
                "خطأ قراءة hijri_offset من Supabase:",
                error
            );

            return hijriOffset;

        }


        // ----------------------------------------
        // عدم وجود الإعداد
        // ----------------------------------------

        if (!data) {

            console.warn(
                "لم يتم العثور على إعداد hijri_offset في Supabase، سيتم استخدام 0"
            );

            return hijriOffset;

        }


        // ----------------------------------------
        // تحويل القيمة إلى رقم
        // ----------------------------------------

        const value =
            Number(
                data.setting_value
            );


        // ----------------------------------------
        // التحقق من القيم المسموحة
        // ----------------------------------------

        if (
            value === -1 ||
            value === 0 ||
            value === 1
        ) {

            hijriOffset = value;

        }

        else {

            console.warn(
                `قيمة hijri_offset غير صحيحة: ${data.setting_value} — سيتم استخدام 0`
            );

            hijriOffset = 0;

        }


        // ----------------------------------------
        // تشخيص
        // ----------------------------------------

        console.log(
            `تم تحميل hijri_offset من Supabase: ${hijriOffset}`
        );

    }

    catch (error) {

        console.error(
            "خطأ تحميل إعدادات التقويم الهجري:",
            error
        );

        hijriOffset = 0;

    }


    return hijriOffset;

}


// ============================================
// الحصول على قيمة التصحيح الحالية
// ============================================

function getHijriOffset() {

    // ----------------------------------------
    // السماح فقط بالقيم الثلاث
    // ----------------------------------------

    if (
        hijriOffset === -1 ||
        hijriOffset === 0 ||
        hijriOffset === 1
    ) {

        return hijriOffset;

    }


    // ----------------------------------------
    // قيمة احتياطية
    // ----------------------------------------

    return 0;

}


// ============================================
// إتاحة الدوال عالميًا
// ============================================

window.loadHijriOffset =
    loadHijriOffset;

window.getHijriOffset =
    getHijriOffset;